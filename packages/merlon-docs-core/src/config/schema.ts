import { z } from 'zod';
import packageJson from '../../package.json' with { type: 'json' };
import { getLocalePack } from '../locale/index.js';

const defaultAboutThisGuideTitle = () => getLocalePack().aboutThisGuideTitle;

const GuideSourceSchema = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('h1Extract'),
    index: z.number().int().positive(),
    preamble: z.object({ promoteToH2: z.string().default(defaultAboutThisGuideTitle) }).optional(),
  }),
  z.object({
    type: z.literal('merge'),
    parts: z.array(
      z.object({
        fromH1Extract: z.number().int().positive(),
        demoteFirstH1: z.boolean().optional(),
      }),
    ),
    preamble: z.object({ promoteToH2: z.string().default(defaultAboutThisGuideTitle) }).optional(),
  }),
  z.object({
    type: z.literal('directory'),
    path: z.string(),
  }),
]);

const GuideSchema = z.object({
  name: z.string(),
  path: z
    .string()
    .optional()
    .describe('Shard directory relative to docs root (default: {docsRoot}/{name}/).'),
  splitLevel: z.number().int().min(1).max(6).default(2),
  source: GuideSourceSchema.optional(),
  compile: z
    .object({
      preambleSection: z.string().default('about-this-guide.md'),
      manifest: z
        .string()
        .default('index.md')
        .describe('Manifest file name; review trees use shards.md.'),
      sectionsHeading: z
        .string()
        .optional()
        .describe('When set, only links after this ## heading in the manifest set compile order.'),
      title: z
        .string()
        .optional()
        .describe('Compile title, injected as a ## heading before the first section.'),
      scopeRoot: z.string().optional(),
      outputFile: z
        .string()
        .optional()
        .describe('Output path for this guide, relative to outputDir or absolute.'),
      includeBanner: z
        .boolean()
        .default(true)
        .describe("Put the top-level banner at the head of this guide's output."),
      sourceTags: z
        .boolean()
        .optional()
        .describe('Wrap each shard in source tags for this guide (default: top-level sourceTags).'),
      hooks: z
        .union([z.array(z.string()), z.record(z.string(), z.boolean())])
        .optional()
        .describe(
          'Named compile hooks. An array replaces the defaults; an object turns named hooks on or off.',
        ),
      crossGuideLinks: z
        .object({
          ignoreGuides: z
            .array(z.string())
            .optional()
            .describe(
              "Guides whose shards this guide's links keep as .md paths instead of #slug targets. A link to a shard this guide stitches still gets its in-document anchor.",
            ),
        })
        .optional()
        .describe('How links to other guides are rewritten when this guide is assembled.'),
      hooksConfig: z
        .object({
          inlineInserts: z
            .object({
              searchRoots: z.array(z.string()).optional(),
            })
            .optional(),
        })
        .optional(),
      stripAnchors: z.boolean().default(true),
      links: z
        .object({
          markBroken: z.boolean().default(true),
        })
        .optional(),
    })
    .optional(),
});

/**
 * The config format version of this release: the version of `@merlon-docs/merlon-docs-core`,
 * which defines the format. A new `merlon.config.json` declares it in `configVersion`.
 */
export const DEFAULT_CONFIG_VERSION: string = packageJson.version;
/** @deprecated Renamed to `DEFAULT_CONFIG_VERSION`; kept until 2.0.0. */
export const DEFAULT_STANDARD_VERSION: string = DEFAULT_CONFIG_VERSION;

const CONFIG_VERSION_DESCRIPTION =
  'Version of @merlon-docs/merlon-docs-core whose config format this file follows.';

export const MerlonConfigSchema = z.object({
  configVersion: z.string().optional().describe(CONFIG_VERSION_DESCRIPTION),
  /** @deprecated Use `configVersion`. */
  standardVersion: z.string().optional().meta({
    description: 'Former name of configVersion, still read until 2.0.0. Use configVersion.',
    deprecated: true,
  }),
  /** @deprecated Use `configVersion`. */
  protocolVersion: z.string().optional().meta({
    description: 'Former name of configVersion, still read until 2.0.0. Use configVersion.',
    deprecated: true,
  }),

  source: z.string().optional(),
  outputDir: z.string().default('_build').describe('Generated output root relative to docs root.'),
  outputFile: z
    .string()
    .optional()
    .describe('Optional stitched monolith filename relative to outputDir.'),
  compileOrder: z.array(z.string()).min(1),
  banner: z
    .string()
    .default('<!-- AUTO-GENERATED by Merlon Docs — edit shards, then run: merlon compile -->\n\n'),
  sourceTags: z
    .boolean()
    .default(true)
    .describe("Wrap each shard's content in HTML source tags indicating its relative path."),
  guides: z.array(GuideSchema).optional(),

  standaloneGuides: z
    .array(z.string())
    .default([])
    .describe(
      'Files or globs (relative to scan root) registered as standalone guides: captured by the coverage scan, with no compile output of their own.',
    ),

  scan: z
    .object({
      gitignore: z
        .boolean()
        .default(true)
        .describe(
          "Honor .gitignore when walking for markdown files: the repository root's inside git, the scan root's outside it.",
        ),
      ignore: z
        .array(z.string())
        .default([])
        .describe('Extra ignore globs beyond the built-in defaults (.git, node_modules, .agents).'),
      root: z
        .string()
        .optional()
        .describe('Walk root for the scan (default: invocation directory).'),
      strict: z
        .boolean()
        .default(false)
        .describe('Fail merlon check when uncaptured files or missing standalone entries exist.'),
    })
    .default({ gitignore: true, ignore: [], strict: false })
    .describe('Repository-wide markdown coverage scan options.'),

  backup: z
    .object({
      enabled: z.boolean().default(false),
      dir: z
        .string()
        .default('.caches/backups')
        .describe('Backup directory relative to outputDir.'),
      ext: z.string().default('').describe('Suffix appended to each backup file name.'),
    })
    .default({
      enabled: false,
      dir: '.caches/backups',
      ext: '',
    })
    .describe('Back up existing compile targets before overwriting them.'),

  refs: z
    .object({
      registryFile: z
        .string()
        .default('.caches/refs.json')
        .describe('Slug registry path relative to outputDir.'),
      slugAlgorithm: z.enum(['github']).default('github'),
    })
    .default({
      registryFile: '.caches/refs.json',
      slugAlgorithm: 'github',
    }),

  lint: z
    .object({
      markdownlint: z
        .object({
          shardsConfig: z.string().optional(),
          compiledConfig: z.string().optional(),
          shardsGlobs: z
            .array(z.string())
            .optional()
            .describe(
              'Shard lint paths relative to docs root (default: the compileOrder guide directories).',
            ),
        })
        .optional(),
      links: z
        .object({
          enabled: z.boolean().default(true),
          severity: z.enum(['error', 'warn']).default('error'),
          target: z.string().optional(),
          config: z.string().optional(),
        })
        .optional(),
      codeExtensions: z
        .array(z.string())
        .default([])
        .describe(
          'Extra code extensions, added to the built-in defaults. A link or path to such a file must resolve, and a symbol in the link label can cite a line in it, as for a stack the defaults leave out or for workflow YAML.',
        ),
      dataExtensions: z
        .array(z.string())
        .default([])
        .describe(
          'Extra data extensions, added to the built-in defaults. A link or path to such a file must resolve; its lines are never cited.',
        ),
      paths: z
        .object({
          severity: z.enum(['off', 'warn', 'error']).default('off'),
          searchRoots: z
            .array(z.string())
            .default([])
            .describe('Extra resolution roots relative to the scan root, tried after it.'),
          generated: z
            .array(z.string())
            .default([])
            .describe(
              'Scan-root-relative prefixes that are real but absent in a clean checkout: build output, caches, vendor-managed installs. Everything beneath a prefix is covered.',
            ),
          vocabulary: z
            .array(z.string())
            .default([])
            .describe(
              "Paths this repository documents without having: names the standard defines for a consumer repository, or another project's tree. Matched exactly, so a file beneath one still has to resolve.",
            ),
        })
        .optional()
        .describe('Backtick-path resolution in documentation prose.'),
    })
    .optional(),

  vale: z
    .object({
      config: z.string().default('.vale.ini'),
      strictMinAlertLevel: z.string().default('error'),
      scanGlobs: z.array(z.string()).optional(),
    })
    .optional(),

  review: z
    .object({
      maxIndexEntries: z
        .number()
        .int()
        .positive()
        .default(12)
        .describe(
          'Most shard links one index group (links under one ## or deeper heading, or before any) may list before index-size fires.',
        ),
      maxShardWords: z
        .number()
        .int()
        .positive()
        .default(2500)
        .describe('Most prose words a shard may hold before long-shard fires.'),
      minDuplicateWords: z
        .number()
        .int()
        .positive()
        .default(25)
        .describe(
          'Fewest words a paragraph needs before duplicate-paragraph compares it across shards.',
        ),
    })
    .default({ maxIndexEntries: 12, maxShardWords: 2500, minDuplicateWords: 25 })
    .describe('Thresholds for merlon review sprawl signals.'),

  diagnostics: z
    .object({
      dir: z
        .string()
        .optional()
        .describe(
          'Directory for split errors.txt and warnings.txt files (relative to outputDir or absolute).',
        ),
      errorsFile: z
        .string()
        .optional()
        .describe(
          'File path for error-severity diagnostics (relative to invocation directory or absolute).',
        ),
      warningsFile: z
        .string()
        .optional()
        .describe(
          'File path for warning-severity diagnostics (relative to invocation directory or absolute).',
        ),
      splitFiles: z
        .boolean()
        .default(false)
        .describe(
          'Write errors.txt and warnings.txt under diagnostics.dir (default .caches/diagnostics under outputDir).',
        ),
    })
    .optional()
    .describe(
      'Optional split diagnostic file sinks for merlon check, merlon compile, and merlon review.',
    ),
});

/**
 * A `merlon.config.json` file. It must declare the config format version it follows, so a reader
 * knows which format it holds; the in-memory `MerlonConfigSchema` doesn't need one.
 */
export const MerlonConfigFileSchema = MerlonConfigSchema.extend({
  configVersion: z.string().describe(CONFIG_VERSION_DESCRIPTION),
}).meta({
  title: 'Merlon Docs configuration',
  description: 'Configuration schema for merlon.config.json, the Merlon Docs config file',
});

export type MerlonConfig = z.infer<typeof MerlonConfigSchema>;
export type MerlonConfigInput = z.input<typeof MerlonConfigSchema>;

